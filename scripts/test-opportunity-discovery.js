const assert = require('node:assert/strict');
const { statusLabels, browse, expired } = require('../js/opportunity-filters');
const { prepare, duplicateOf, importRows } = require('./import-ofy-discovery');
const normalizer = require('../backend/services/opportunitySources/manualSource');
const manifest = require('../data/opportunities-ofy-2026-09-29.json');
const day = '2026-09-29';
const unknown = { ...manifest.additions[3], id: 'unknown' };
const open = { ...manifest.additions[0], id: 'open', application_deadline:'2099-01-01' };
const upcoming = { ...unknown, id:'upcoming', discovery:{...unknown.discovery,deadline_status:'upcoming'} };
assert.deepEqual(statusLabels(open, day), ['Open now']);
assert.deepEqual(statusLabels(unknown, day), ['Check deadline','Check eligibility','Application link unavailable']);
assert.ok(statusLabels(upcoming, day).includes('Upcoming'));
assert.deepEqual(browse([unknown, upcoming, open]).opportunities.map(x=>x.id), ['open','upcoming','unknown']);
assert.equal(browse([unknown],{country:'global'}).total, 0);
assert.equal(browse([unknown],{country:'SG'}).total, 0);
assert.equal(browse([open],{country:'SG'}).total, 1);
assert.equal(browse([{...open, application_deadline:'2020-01-01'}]).total, 0);
assert.equal(expired({...unknown,discovery:{...unknown.discovery,deadline_status:'closed'}},day),true);
const normalized = normalizer.normaliseOpportunity({...unknown,application_url:null,status:'published'},null);
assert.equal(normalized.verification_status,'pending_review');
assert.equal(normalized.verified_at,null);
assert.equal(normalized.application_method,'external');
assert.equal(normalized.internal_application_enabled,false);
assert.equal(normalized.application_deadline,null);
assert.throws(()=>prepare({...open,discovery:{...open.discovery,deadline_status:'unknown'}}),/must be null/);
assert.throws(()=>prepare({...open,discovery:{...open.discovery,last_checked_at:null}}),/last-checked/);
for (const item of manifest.additions) prepare(item);
const original = {...open, id:'existing', verification_status:'verified', updated_at:'2026-09-28T00:00:00Z'};
assert.equal(duplicateOf([original], {...open,source_url:open.source_url+'/?utm_source=test'}).id,'existing');
// Unknown source evidence must never replace a verified listing or its ID.
(async()=>{
  let patch;
  const client = {from(){return {update(value){patch=value;return this;},eq(){return this;},async select(){return {data:[{id:'existing'}]};}};}};
  const report = await importRows(client, [{...manifest.additions[0],application_deadline:null,discovery:{...unknown.discovery, discovered_url:unknown.source_url}}], [original]);
  assert.equal(report.merged.length,1);
  assert.deepEqual(Object.keys(patch),['discovery_sources']);
  assert.equal(original.verification_status,'verified');
  assert.equal(original.application_deadline,'2099-01-01');
  const once = await importRows(null,manifest.additions,[]);
  assert.equal(once.added.length,10);
  const twice = await importRows(null,manifest.additions,manifest.additions.map(prepare));
  assert.equal(twice.added.length,0);
  assert.equal(twice.merged.length,10);
  console.log('Discovery passed: unknown evidence, ranking, expiry, geography, validation, repeat imports and non-destructive duplicate merging.');
})().catch(error=>{console.error(error);process.exitCode=1;});
